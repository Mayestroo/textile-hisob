  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id VARCHAR(100) NOT NULL,
  worker_id INTEGER NOT NULL,
  telegram_id VARCHAR(24) NOT NULL,
  actor_telegram_id VARCHAR(24) NOT NULL,
  event_type VARCHAR(16) NOT NULL CHECK (event_type = 'UNBOUND'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT worker_binding_events_telegram_id_check CHECK (telegram_id ~ '^[0-9]{1,24}$'),
  CONSTRAINT worker_binding_events_actor_id_check CHECK (actor_telegram_id ~ '^[0-9]{1,24}$'),
  CONSTRAINT worker_binding_events_worker_fk FOREIGN KEY (company_id, worker_id)
    REFERENCES workers(company_id, id) ON DELETE RESTRICT
);

